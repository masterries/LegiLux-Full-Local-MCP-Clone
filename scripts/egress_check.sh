#!/usr/bin/env bash
# Airgap egress check of the runtime services (PLAN §11.6 / D15; method and results: docs/dev/e2e-2026-10-17.md).
#
# Starts db + db-load + mcp + ollama + lgx-streamlit as a separate compose project (legilux-egress) from
# deploy/compose.dev.yml plus a generated override:
#   - every service sits only on the `backend` network (no `edge`, no published port); --mode internal (default)
#     keeps it `internal: true` (no gateway route in the containers); --mode routed makes it a plain bridge WITHOUT
#     masquerading, so that any connection to a non-local address really leaves the container and is counted below;
#   - a DNS sentinel (pinned CoreDNS, logs every query, answers NXDOMAIN, no upstream) is every service's resolver;
#   - iptables counters (inserted before the first container starts): DOCKER-USER DROP for packets from the bridge to
#     any other interface, INPUT DROP for NEW connections from the bridge to the host itself.
# Then a scripted session through headless Chromium (scripts/ui_browser.cjs, every page request recorded): startup,
# one Chat answer (real LLM on CPU) and one Direct search. Afterwards positive controls prove that each probe sees an
# attempt (a canary DNS lookup, a TCP connect to TEST-NET-1 and one to the bridge gateway, made from lgx-streamlit).
# PASS = 0 sentinel queries, 0 packets on the counter rules and 0 non-local browser requests during the session.
#
# Usage: scripts/egress_check.sh [--mode internal|routed] [--keep] [--no-chat] [--question TEXT] [--direct TEXT]
#                                [--out DIR] [--subnet 172.31.250.0/24] [--dry-run]
# (--dry-run writes the override + Corefile and prints the rendered compose config; nothing is started.)
# Needs: root (iptables), docker compose, the images built by `make dev-up` (lgx.local/lgx-{db,mcp,streamlit}:dev),
# the Ollama image + model volume (`make ollama-pull`), the pinned CoreDNS image (deploy/images.lock, pulled through
# mirror.gcr.io), the sample bundle in data/bundles/, node with the `playwright` npm package and its Chromium.
# It never builds or pulls (compose --no-build --pull never). The dev stack (project legilux-dev) is left alone.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MODE=internal
KEEP=0
DRY=0
CHAT=1
QUESTION="Que dit l'article L. 121-1 du Code du travail ?"
DIRECT="art. L. 121-1 C. trav."
SUBNET=172.31.250.0/24
OUT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --mode) MODE=$2; shift 2 ;;
    --keep) KEEP=1; shift ;;
    --dry-run) DRY=1; shift ;;
    --no-chat) CHAT=0; shift ;;
    --question) QUESTION=$2; shift 2 ;;
    --direct) DIRECT=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    --subnet) SUBNET=$2; shift 2 ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "egress_check: unknown option $1" >&2; exit 2 ;;
  esac
done
case "$MODE" in internal|routed) ;; *) echo "egress_check: --mode internal|routed" >&2; exit 2 ;; esac

PROJECT=legilux-egress
BRIDGE=br-lgx-egress
TAG=lgx-egress-check
PREFIX=${SUBNET%.*}                       # 172.31.250
SENTINEL_IP=$PREFIX.53
GATEWAY_IP=$PREFIX.1
COREDNS_IMAGE=${LGX_COREDNS_IMAGE:-mirror.gcr.io/coredns/coredns:1.14.7@sha256:7efd3c635b03efd68c4e8398fc45f0d993d0e9ab016f72c1cefb0fd6d01aa286}
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
OUT=${OUT:-$ROOT/data/reports/egress/$STAMP-$MODE}
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
COMPOSE=(docker compose -p "$PROJECT" -f "$ROOT/deploy/compose.dev.yml" -f "$OUT/compose.egress.yml" --profile cpu)
log() { printf '[egress] %s\n' "$*" >&2; }

# ------------------------------------------------------------------------------------------------ prerequisites
[ "$(id -u)" = 0 ] || { log "needs root (iptables)"; exit 2; }
command -v iptables >/dev/null || { log "iptables not found"; exit 2; }
NODE_PATH=${NODE_PATH:-$(npm root -g 2>/dev/null || true)}
export NODE_PATH
node -e "require('playwright')" 2>/dev/null || { log "node + the playwright npm package are required"; exit 2; }
for img in lgx.local/lgx-db:dev lgx.local/lgx-mcp:dev lgx.local/lgx-streamlit:dev "$COREDNS_IMAGE"; do
  docker image inspect "$img" >/dev/null 2>&1 || { log "image $img missing (make dev-up / docker pull)"; exit 2; }
done
docker volume inspect "${LGX_DEV_OLLAMA_VOLUME:-legilux-dev-ollama}" >/dev/null 2>&1 \
  || { log "Ollama model volume missing: make ollama-pull"; exit 2; }

# ------------------------------------------------------------------------------------------------ generated files
cat > "$OUT/Corefile" <<'EOF'
. {
    log
    errors
    template ANY ANY {
        rcode NXDOMAIN
    }
}
EOF
chmod 0644 "$OUT/Corefile"
if [ "$MODE" = internal ]; then NET_OPTS="internal: true"; else NET_OPTS="internal: false"; fi
DNS="dns: [\"$SENTINEL_IP\"]"
DEP="egress-sentinel: { condition: service_started }"
cat > "$OUT/compose.egress.yml" <<EOF
# generated by scripts/egress_check.sh --mode $MODE ($STAMP)
networks:
  backend:
    $NET_OPTS
    driver_opts:
      com.docker.network.bridge.name: $BRIDGE
      com.docker.network.bridge.enable_ip_masquerade: "false"
    ipam: { config: [{ subnet: "$SUBNET", gateway: "$GATEWAY_IP" }] }
volumes:
  pgdata: { name: legilux-egress-pgdata }
  ollama-models: { name: "${LGX_DEV_OLLAMA_VOLUME:-legilux-dev-ollama}", external: true }
services:
  egress-sentinel:
    image: "$COREDNS_IMAGE"
    pull_policy: never
    command: ["-conf", "/etc/coredns/Corefile"]
    read_only: true
    cap_drop: [ALL]
    cap_add: [NET_BIND_SERVICE]                         # /coredns carries this file capability; exec fails without it
    security_opt: ["no-new-privileges:true"]
    volumes: ["$OUT/Corefile:/etc/coredns/Corefile:ro"]
    networks: { backend: { ipv4_address: "$SENTINEL_IP" } }
  db: { $DNS, pull_policy: never, depends_on: { $DEP } }
  db-load: { $DNS, pull_policy: never, depends_on: { $DEP } }
  mcp: { $DNS, pull_policy: never, depends_on: { $DEP }, networks: !override [backend], ports: !reset [] }
  ollama: { $DNS, pull_policy: never, depends_on: { $DEP } }
  lgx-streamlit:
    $DNS
    pull_policy: never
    depends_on: { $DEP }
    networks: !override [backend]
    ports: !reset []
    environment: { LGX_LLM_TIMEOUT_S: "600", LGX_TURN_BUDGET_S: "1200" }
EOF

if [ "$DRY" = 1 ]; then "${COMPOSE[@]}" config; exit 0; fi

# ------------------------------------------------------------------------------------------------ counters
rules() {  # $1 = -I | -D
  iptables "$1" DOCKER-USER -i "$BRIDGE" ! -o "$BRIDGE" -m comment --comment "$TAG-fwd" -j DROP
  iptables "$1" INPUT -i "$BRIDGE" -m conntrack --ctstate NEW -m comment --comment "$TAG-host" -j DROP
}
count() {  # $1 = chain, $2 = comment → packets
  iptables -L "$1" -v -x -n | awk -v t="$2" '$0 ~ t {s += $1} END {print s + 0}'
}
cleanup() {
  set +e
  while iptables -C DOCKER-USER -i "$BRIDGE" ! -o "$BRIDGE" -m comment --comment "$TAG-fwd" -j DROP 2>/dev/null; do
    iptables -D DOCKER-USER -i "$BRIDGE" ! -o "$BRIDGE" -m comment --comment "$TAG-fwd" -j DROP
  done
  while iptables -C INPUT -i "$BRIDGE" -m conntrack --ctstate NEW -m comment --comment "$TAG-host" -j DROP 2>/dev/null; do
    iptables -D INPUT -i "$BRIDGE" -m conntrack --ctstate NEW -m comment --comment "$TAG-host" -j DROP
  done
  if [ "$KEEP" = 0 ]; then "${COMPOSE[@]}" down -v --remove-orphans >/dev/null 2>&1; fi
}
trap cleanup EXIT

"${COMPOSE[@]}" down -v --remove-orphans >/dev/null 2>&1 || true   # leftovers of an earlier run
iptables -N DOCKER-USER 2>/dev/null || true
rules -I
log "mode $MODE · bridge $BRIDGE ($SUBNET) · sentinel $SENTINEL_IP · output $OUT"

# ------------------------------------------------------------------------------------------------ 1. startup
t0=$(date +%s)
"${COMPOSE[@]}" up -d --no-build --pull never --wait --wait-timeout 600 >"$OUT/compose-up.log" 2>&1 \
  || { log "compose up failed (see $OUT/compose-up.log)"; tail -20 "$OUT/compose-up.log" >&2; exit 1; }
log "startup: healthy after $(( $(date +%s) - t0 )) s"
"${COMPOSE[@]}" ps --format '{{.Service}} {{.Status}}' > "$OUT/compose-ps.txt"
UI_IP=$(docker inspect -f "{{(index .NetworkSettings.Networks \"${PROJECT}_backend\").IPAddress}}" "$PROJECT-lgx-streamlit-1")
docker exec "$PROJECT-lgx-streamlit-1" cat /proc/net/route > "$OUT/streamlit-routes.txt"
STARTUP_FWD=$(count DOCKER-USER "$TAG-fwd"); STARTUP_HOST=$(count INPUT "$TAG-host")
STARTUP_DNS=$(docker logs "$PROJECT-egress-sentinel-1" 2>&1 | grep -c '"' || true)

# ------------------------------------------------------------------------------------------------ 2. session
BROWSER_ARGS=(--url "http://$UI_IP:8501" --direct "$DIRECT" --requests "$OUT/browser-requests.json")
[ "$CHAT" = 1 ] && BROWSER_ARGS+=(--chat "$QUESTION" --chat-timeout-s 1200)
log "browser session against http://$UI_IP:8501 (chat: $CHAT)"
t1=$(date +%s)
BROWSER_RC=0
node "$ROOT/scripts/ui_browser.cjs" "${BROWSER_ARGS[@]}" --shots "$OUT/shots" 2>"$OUT/browser.log" || BROWSER_RC=$?
cat "$OUT/browser.log" >&2
SESSION_S=$(( $(date +%s) - t1 ))
sleep 5
FWD=$(count DOCKER-USER "$TAG-fwd"); HOST=$(count INPUT "$TAG-host")
docker logs "$PROJECT-egress-sentinel-1" > "$OUT/sentinel.log" 2>&1
DNS_Q=$(grep -c '"' "$OUT/sentinel.log" || true)
FOREIGN=$(python3 -c "import json,sys; print(len(json.load(open(sys.argv[1]))['foreign']))" "$OUT/browser-requests.json")
REQS=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['requests_total'])" "$OUT/browser-requests.json")
iptables -L DOCKER-USER -v -x -n > "$OUT/iptables-docker-user.txt"
iptables -L INPUT -v -x -n | grep -E "Chain|pkts|$TAG" > "$OUT/iptables-input.txt"
"${COMPOSE[@]}" logs --no-color > "$OUT/compose-logs.txt" 2>&1 || true

# ------------------------------------------------------------------------------------------------ 3. positive controls
UI_CTR="$PROJECT-lgx-streamlit-1"
CANARY=lgx-egress-canary.example
docker exec "$UI_CTR" python -c "
import socket, sys
def probe(what, fn):
    try:
        fn(); print(what, 'connected')
    except Exception as e:
        print(what, type(e).__name__, getattr(e, 'errno', ''), e)
probe('dns', lambda: socket.getaddrinfo('$CANARY', 443))
probe('tcp 192.0.2.1:443', lambda: socket.create_connection(('192.0.2.1', 443), timeout=3))
probe('tcp $GATEWAY_IP:9', lambda: socket.create_connection(('$GATEWAY_IP', 9), timeout=3))
" > "$OUT/controls.txt" 2>&1 || true
sleep 1
C_FWD=$(( $(count DOCKER-USER "$TAG-fwd") - FWD )); C_HOST=$(( $(count INPUT "$TAG-host") - HOST ))
C_DNS=$(docker logs "$PROJECT-egress-sentinel-1" 2>&1 | grep -c "$CANARY" || true)
sed 's/^/[egress] control: /' "$OUT/controls.txt" >&2

# ------------------------------------------------------------------------------------------------ verdict
PASS=1
[ "$FWD" = 0 ] && [ "$HOST" = 0 ] && [ "$DNS_Q" = 0 ] && [ "$FOREIGN" = 0 ] && [ "$BROWSER_RC" = 0 ] || PASS=0
CONTROLS_OK=1
[ "$C_DNS" -ge 1 ] && [ "$C_HOST" -ge 1 ] || CONTROLS_OK=0
if [ "$MODE" = routed ] && [ "$C_FWD" -lt 1 ]; then CONTROLS_OK=0; fi
python3 - "$OUT/summary.json" <<EOF
import json, sys
json.dump({
  "mode": "$MODE", "bridge": "$BRIDGE", "subnet": "$SUBNET", "stamp": "$STAMP",
  "startup": {"dns_queries": $STARTUP_DNS, "fwd_packets": $STARTUP_FWD, "host_packets": $STARTUP_HOST},
  "session": {"seconds": $SESSION_S, "browser_rc": $BROWSER_RC, "chat": bool($CHAT), "browser_requests": $REQS,
              "foreign_requests": $FOREIGN},
  "totals": {"dns_queries": $DNS_Q, "fwd_packets": $FWD, "host_packets": $HOST},
  "controls": {"dns_canary_logged": $C_DNS, "fwd_packets": $C_FWD, "host_packets": $C_HOST},
  "pass": bool($PASS), "controls_ok": bool($CONTROLS_OK),
}, open(sys.argv[1], "w"), indent=2)
EOF
log "startup: dns $STARTUP_DNS · fwd $STARTUP_FWD · host $STARTUP_HOST"
log "session ($SESSION_S s): dns queries $DNS_Q · DOCKER-USER pkts $FWD · INPUT pkts $HOST · browser requests $REQS (non-local $FOREIGN)"
log "controls: canary lookups $C_DNS · DOCKER-USER +$C_FWD · INPUT +$C_HOST ($( [ "$MODE" = internal ] && echo 'internal: no route, connect fails in the container' || echo 'routed: the connect is dropped and counted'))"
if [ "$PASS" = 1 ] && [ "$CONTROLS_OK" = 1 ]; then log "PASS (summary: $OUT/summary.json)"; exit 0; fi
log "FAIL (pass=$PASS controls_ok=$CONTROLS_OK; see $OUT)"; exit 1
